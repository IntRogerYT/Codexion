#include "../../main.h"

int	ft_strisalpha(char *s)
{
	int	i;

	i = 0;
	while (s[i])
	{
		if (!(s[i] >= 'A' && s[i] <= 'Z') && !(s[i] >= 'a' && s[i] <= 'z'))
			return (0);
		i++;
	}
	return (1);
}
